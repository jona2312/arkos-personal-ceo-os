/* Development-only browser test. Requires Playwright; not a runtime dependency. */
const assert = require('node:assert/strict');
const {spawn} = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {chromium} = require(require.resolve('playwright', {paths: [process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES || process.cwd(), ...require.resolve.paths('playwright')]}));
const root = path.resolve(__dirname, '..');
const stateDir = fs.mkdtempSync(path.join(os.tmpdir(), 'arkos-center-e2e-'));
const evidence = path.join(root,'docs','task-center','screenshots');
fs.mkdirSync(evidence, {recursive:true});
const server=spawn(process.env.ARKOS_TEST_PYTHON || 'python',['-m','arkos_pilot.task_center','--state-dir',stateDir,'--port','0','--no-browser'],{cwd:root,stdio:['ignore','pipe','pipe']});
let browser;
async function main(){
  const url=await new Promise((resolve,reject)=>{let buffer='';const timer=setTimeout(()=>reject(new Error('Local server did not start')),10000);server.stdout.on('data',chunk=>{buffer+=chunk.toString();const match=buffer.match(/http:\/\/127\.0\.0\.1:\d+\/#key=[\w-]+/);if(match){clearTimeout(timer);resolve(match[0]);}});server.on('error',reject);server.on('exit',code=>{clearTimeout(timer);reject(new Error('Server stopped: '+code));});});
  browser=await chromium.launch({headless:true, ...(process.env.ARKOS_TEST_CHROMIUM ? {executablePath:process.env.ARKOS_TEST_CHROMIUM} : {}), ...(process.env.ARKOS_TEST_CHROMIUM_ARGS ? {args:JSON.parse(process.env.ARKOS_TEST_CHROMIUM_ARGS)} : {})});
  const page=await browser.newPage({viewport:{width:1512,height:1050},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(url);
  await page.getByText('Esta PC · conectada',{exact:true}).waitFor();
  assert.equal(await page.locator('.task-card').count(),0);
  async function createNote(text){await page.getByRole('button',{name:'Nueva tarea'}).first().click();await page.getByLabel('Contenido de la nota').fill(text);await page.getByRole('button',{name:'Guardar tarea',exact:true}).click();await page.locator('#task-dialog').waitFor({state:'hidden'});}
  const content='Plan para mañana\n1. Revisar la propuesta\n2. Organizar documentos\n3. Preparar la reunión';
  await createNote(content);
  await page.locator('#home-board .task-card').getByRole('button',{name:'Ver tarea'}).click();
  assert.equal(await page.locator('#review-content').textContent(),content);
  await page.getByRole('button',{name:'Aprobar esta tarea',exact:true}).click();
  await page.locator('#home-board .task-card').getByRole('button',{name:'Revisar y ejecutar'}).click();
  await page.getByRole('button',{name:'Ejecutar esta tarea',exact:true}).click();
  await page.locator('#home-board .task-card').getByRole('button',{name:'Abrir resultado'}).waitFor();
  await page.locator('#home-board .task-card').getByRole('button',{name:'Abrir resultado'}).click();
  await page.locator('#result-dialog').waitFor({state:'visible'});
  assert.equal(await page.locator('#result-text').textContent(),content+'\n');
  await page.locator('#result-dialog').getByRole('button',{name:'Cerrar',exact:true}).click();
  await createNote('Preparar propuesta comercial\nRevisar alcance y próximos pasos antes de enviar.');
  await createNote('Ordenar ideas del proyecto\nElegir tres prioridades para la próxima reunión.');
  await page.locator('#home-board .task-card').filter({hasText:'Ordenar ideas del proyecto'}).getByRole('button',{name:'Ver tarea'}).click();
  await page.getByRole('button',{name:'Aprobar esta tarea',exact:true}).click();
  // Verify user content never turns into markup or script.
  await createNote('<img src=x onerror="window.arkosInjected=true">');
  assert.equal(await page.evaluate(()=>window.arkosInjected),undefined);
  await page.locator('#home-board .task-card').filter({hasText:'<img src=x'}).getByRole('button',{name:'Ver tarea'}).click();
  await page.getByRole('button',{name:'Cancelar tarea',exact:true}).click();
  await page.reload();await page.getByText('Esta PC · conectada',{exact:true}).waitFor();
  assert.equal(await page.locator('#stat-completed').textContent(),'1');
  assert.equal(await page.locator('#stat-review').textContent(),'1');
  assert.equal(await page.locator('#stat-active').textContent(),'1');
  await page.screenshot({path:path.join(evidence,'desktop-dark.png'),fullPage:true});
  await page.getByRole('button',{name:'Personalizar apariencia',exact:true}).click();
  await page.getByRole('button',{name:'Claro',exact:false}).click();
  await page.getByRole('button',{name:'Rojo',exact:true}).click();
  await page.locator('#appearance-dialog').getByRole('button',{name:'Cerrar',exact:true}).click();
  await page.reload();await page.getByText('Esta PC · conectada',{exact:true}).waitFor();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
  assert.equal(await page.locator('html').getAttribute('data-accent'),'red');
  await page.screenshot({path:path.join(evidence,'desktop-light.png'),fullPage:true});
  await page.getByRole('button',{name:'Personalizar apariencia',exact:true}).click();
  await page.getByRole('button',{name:'Oscuro',exact:false}).click();await page.getByRole('button',{name:'Azul',exact:true}).click();
  await page.locator('#appearance-dialog').getByRole('button',{name:'Cerrar',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:path.join(evidence,'mobile-dark.png'),fullPage:true});
  await page.screenshot({path:path.join(evidence,'mobile-viewport.png')});
  await page.locator('[data-page="tasks"]').click();
  await page.getByLabel('Buscar una tarea').fill('Plan para mañana');
  assert.equal(await page.locator('#tasks-list .task-card').count(),1);
  await page.locator('[data-page="conversation"]').click();
  await page.getByLabel('¿Qué te gustaría resolver?').fill('Quiero recortar un video');
  await page.getByRole('button',{name:'Preparar pedido'}).click();
  await page.locator('#proposal-result').waitFor({state:'visible'});
  assert.match(await page.locator('#proposal-next').textContent(),/duración/);
  await page.locator('[data-page="connections"]').click();
  assert.match(await page.locator('#connections-grid').textContent(),/WhatsApp/);
  assert.match(await page.locator('#connections-grid').textContent(),/Sincronización pendiente/);
  // Same session must not expose its data to a browser without its launch key.
  const outsider=await browser.newContext();const outsidePage=await outsider.newPage();
  await outsidePage.goto(url.split('#')[0]);
  await outsidePage.locator('#connection-banner').waitFor({state:'visible'});
  assert.match(await outsidePage.locator('#connection-banner').textContent(),/enlace de esta sesión/);
  await outsider.close();
  assert.deepEqual(errors,[]);
  // Shutdown must become visible; stale data must not masquerade as a live PC.
  server.kill();await new Promise(resolve=>server.once('exit',resolve));
  await page.getByRole('button',{name:'Actualizar tareas',exact:true}).click();
  await page.getByText('Sin conexión local',{exact:true}).first().waitFor({state:'attached'});
  assert.equal(await page.locator('#connection-banner').isVisible(),true);
  console.log('PASS: browser → API → SQLite → approved execution → artifact; persistence, cancellation, XSS rendering, mobile layout, theme persistence, search, proposals, pending connections, unauthorized client, offline state.');
}
main().catch(e=>{console.error(e.message);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();if(server.exitCode===null&&!server.killed){server.kill();await new Promise(r=>server.once('exit',r));}fs.rmSync(stateDir,{recursive:true,force:true});});
